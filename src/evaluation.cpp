/**
 * Evaluation function for the engine
 * Does not check checkmate or draw
 *
 * @param board Board object
 * @returns evaluation score with respect to who's turn it is
 */
int evaluate(BoardWrapper &br) {

    int eval = 0;
    int piece_value, colour;

    for (int sq = 0; sq < 64; sq++) {

        const chess::Piece& piece = br.board.at(chess::Square(sq));

        if (piece == chess::Piece::NONE)
            continue;

        colour = piece.color() == chess::Color::WHITE ? 1 : -1;
        const chess::PieceType& type = piece.type();

        if (type == chess::PieceType::KING) {
            piece_value =  colour * (KING_VALUE + (piece.color() == chess::Color::WHITE ? KING : R_KING)[sq]);

        } else if (type == chess::PieceType::QUEEN) {
            piece_value =  colour * (QUEEN_VALUE + (piece.color() == chess::Color::WHITE ? QUEEN : R_QUEEN)[sq]);

        } else if (type == chess::PieceType::ROOK) {
            piece_value = colour * (ROOK_VALUE + (piece.color() == chess::Color::WHITE ? ROOK : R_ROOK)[sq]);

        } else if (type == chess::PieceType::BISHOP) {
            piece_value = colour * (BISHOP_VALUE + (piece.color() == chess::Color::WHITE ? BISHOP : R_BISHOP)[sq]);

        } else if (type == chess::PieceType::KNIGHT) {
            piece_value = colour * (KNIGHT_VALUE + (piece.color() == chess::Color::WHITE ? KNIGHT : R_KNIGHT)[sq]);

        } else if (type == chess::PieceType::PAWN) {
            piece_value = colour * (PAWN_VALUE + (piece.color() == chess::Color::WHITE ? PAWN : R_PAWN)[sq]);
        }

        eval += piece_value;

    }

    return br.board.sideToMove() == chess::Color::WHITE ? eval : -eval;
}
